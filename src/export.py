from __future__ import annotations

from datetime import datetime

import markdown2


def generate_html(messages: list[dict[str, str]], title: str = "KG-RAG AI Tutor Chat History") -> str:
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    chat_content = ""
    interaction_count = 0

    for message in messages:
        role_class = "user" if message["role"] == "user" else "assistant"
        label = "Student" if role_class == "user" else "AI Tutor"
        if role_class == "user":
            interaction_count += 1
        formatted_content = markdown2.markdown(message["content"]).replace("\\n", "<br>")
        chat_content += (
            f"<div class='message {role_class}'><span class='label'>{label}</span>{formatted_content}</div>"
        )

    return f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>{title}</title>
  <style>
    body {{ font-family: Georgia, serif; background: #f7f4f8; margin: 0; }}
    .container {{ max-width: 900px; margin: 24px auto; background: white; border-radius: 8px; overflow: hidden; box-shadow: 0 2px 10px rgba(0,0,0,.08); }}
    .header, .footer {{ background: #2d1b4e; color: white; padding: 16px 24px; }}
    .meta {{ color: #ddd; font-size: 0.9rem; }}
    .message {{ padding: 14px 24px; border-bottom: 1px solid #eee; line-height: 1.55; }}
    .user {{ background: #f3eef7; }}
    .assistant {{ background: #fff; }}
    .label {{ display: inline-block; font-weight: bold; color: #6d2c8f; margin-bottom: 6px; }}
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <h1>{title}</h1>
      <div class="meta">Generated on: {timestamp}</div>
      <div class="meta">Total Q&amp;A interactions: {interaction_count}</div>
    </div>
    {chat_content}
    <div class="footer">Generated by KG-RAG AI Tutor (ICEIT 2025).</div>
  </div>
</body>
</html>"""